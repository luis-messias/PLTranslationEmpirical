from collections import Counter

def analyze_data(data):
    """
    Analyzes a list of numbers to find frequency, min, max, mean, and median.

    Args:
        data (list): A list of numbers (integers or floats).

    Returns:
        dict: A dictionary containing the analysis results.
    """
    if not data:
        return {
            "count": 0,
            "min": None,
            "max": None,
            "mean": None,
            "median": None,
            "frequency": {}
        }

    # 1. Count
    count = len(data)

    # 2. Min and Max
    min_val = min(data)
    max_val = max(data)

    # 3. Mean (Average)
    mean_val = sum(data) / count

    # 4. Median
    sorted_data = sorted(data)
    median_val = (sorted_data[count // 2] + sorted_data[count - 1 - (count // 2)]) / 2 if count % 2 == 0 else sorted_data[count // 2]

    # 5. Frequency
    frequency = Counter(data)

    return {
        "count": count,
        "min": min_val,
        "max": max_val,
        "mean": mean_val,
        "median": median_val,
        "frequency": dict(frequency)
    }

