import hashlib

def compute_output(input_numbers):
    # Convert input numbers to a string representation
    input_str = ','.join(map(str, input_numbers))
    
    # Use SHA-256 hash and convert to integer
    hash_obj = hashlib.sha256(input_str.encode())
    hash_hex = hash_obj.hexdigest()
    
    # Take the first 9 digits of the hash as integer
    result = int(hash_hex[:9], 16)
    
    return result

